    p = DOCS / DOC
    assert p.exists(), ("找不到 %s\n⇒ 本脚本是 **Windows 侧工具**：`md文档/` 在 git 仓库之外（仓库的上一级）。"
                        "\n   确需在别处生成：`--docs-dir <new_contribution_2 的路径>`。" % p)
