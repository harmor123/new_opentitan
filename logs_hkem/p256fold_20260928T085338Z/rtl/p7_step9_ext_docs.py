    ap.add_argument("--check", action="store_true")
    ap.add_argument("--docs-dir")
    args = ap.parse_args()
    global DOCS
    if args.docs_dir:
        DOCS = pathlib.Path(args.docs_dir)
    DOCS = pathlib.Path(DOCS)

