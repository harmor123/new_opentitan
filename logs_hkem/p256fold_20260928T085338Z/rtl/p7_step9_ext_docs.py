    psr = PSR.read_text(encoding="utf-8", errors="replace")
    rst = RST.read_text(encoding="utf-8", errors="replace")
    for pat, what in ((r'\("net",\s*r"\^"', "power.net"), (r'\("int",', "power.int"),
                      (r'\("leak",', "power.leak"), (r'\("voltage",', "units.voltage"),
                      (r'\("capacitance",', "units.capacitance"), (r'\("time",', "units.time"),
                      (r'\("dynamic",', "units.dynamic")):
        assert re.search(pat, psr), "parse-syn-report.py 里找不到 %s ⇒ §8.13.6「甲」失效" % what
    m = re.search(r"^report_power\s+-hier -nosplit", rst, re.M)
    assert m, "run-syn.tcl 里找不到 report_power -hier -nosplit ⇒ §8.13.6「甲」失效"
    ln = rst[:m.start()].count("\n") + 1

    L = []
    L.append("#### 8.13.6 外部对照：本仓库既有口径 + 公开文献 + 三条负结果（2026-09-30）")
    L.append("")
    L.append("**甲、本仓库自己的功耗口径（本机可核 ⇒ 本节最强证据）**")
    L.append("")
    L.append("上游 OTBN 综合流程走 **Design Compiler**：`hw/syn/tools/dc/run-syn.tcl:%d` "
             "`report_power -hier -nosplit > power.rpt`；仓库自带解析器把它归成**三分量 + 单位**："
             "`power = {net, int, leak}`（`hw/syn/tools/dc/parse-syn-report.py` 的 `_extract_power`）"
             "并**单独解析** `Voltage / Capacitance / Time / Dynamic Power Units`（同文件 `_extract_units`）✓。" % ln)
    L.append("")
    L.append("⇒ 我们的 A 档（`P_sw / P_int / P_leak` 三分量 + **逐项**从 liberty 解析单位）**与仓库既有口径同构** ✓；"
             "差别**只在工具**：DC 需商业许可、本环境没有 ⇒ 用 yosys/ABC 网表 + 解析式估计。"
             "**不得**把 8.13.1 的表写成 DC/签核结果 ✗（同一纪律见 §8.4 第 1 条）。")
    L.append("")
    L.append("**乙、公开文献口径对照（只回答「我们的做法是否落在领域惯例内」；不引入任何外部数字 ✓）**")
    L.append("")
    L.append("> ⚠ 下列条目由检索代理下载 PDF 原文摘录（附 URL），但**本机网络策略拦截 ⇒ 未能二次复核** ✗"
             "⇒ 只作口径对照，**不作任何本项目数字的依据** ✓。")
    L.append("")
    L.append("| 问 | 领域惯例（出处） | 我们的对应 |")
    L.append("|---|---|---|")
    L.append("| 用什么工具 | 开源路线已足够：TCHES 2026 FrodoKEM 全程 OpenROAD（“Area, Power, and Frequency "
             "estimates are extracted from final report generated by the OpenROAD toolchain”；"
             "`tches.v2026.i3.881-907`）。商业路线：Cadence Joules（RISQ-V，`tches.v2020.i4`）、"
             "DC + PrimeTime（ePrint 2025/308） | 无商业许可 ⇒ 开源链路（§8.13.1/8.13.2）✓ |")
    L.append("| 活动率从哪来 | 主流是**仿真回标**：门级 **SAIF**→Joules（RISQ-V）、综合后仿真逐门收集→PrimeTime"
             "（ePrint 2025/308）；无仿真时用 **vectorless 默认**（OpenSTA 文档：输入默认 activity 0.1、"
             "duty 0.5） | **A 档 α=0.10 档恰为该默认值** ✓；α=0.25/0.5 是我们另加的档（见 8.13.2 对照）|")
    L.append("| 双口径并列 | CMALU（ICCAD'26，ePrint 2026/1423）同篇并列 **SAIF 口径**与 **vectorless 口径**，"
             "并明说后者是保守上界 | **与我们的 A/B 两档同构** ✓（A 档=上界、B 档=实测活动率）|")
    L.append("| 报什么粒度 | 事实标准是 `cycles + power + energy/op`（Sapphire，TCHES 2019(4) 表 7）；"
             "leakage **单独一列**（RISQ-V 表 8 的四分量） | 8.13.3 的分列 ✓；`energy/op` 见 8.13.1 表 A-2 ✓ |")
